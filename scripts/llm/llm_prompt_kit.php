    /* ============================================================
     * 四、温度策略（Temperature Strategy）
     *   按任务性质分档，不再一律 0.7。
     * ============================================================ */
    public static function temperature(string $task): float
    {
        $map = [
            'flagship'        => 0.45,  // 长文要求结构稳定
            'weak_post'       => 0.55,  // 单篇文章需要一些变化
            'hub'             => 0.50,  // 聚合页要严谨
            'geo'             => 0.55,  // 地域内容要点真实
            'monthly_brief'   => 0.40,  // 行情提要要保守
            'b2b_meta'        => 0.60,  // 营销文案可以稍灵活
            'topic'           => 0.55,
        ];
        return $map[$task] ?? 0.55;
    }

    /* ============================================================
     * 五、组装器（Builder）
     *   把 role + rules + body + checklist 拼成完整 system / user。
     * ============================================================ */
    public static function buildSystem(string $roleKey, array $ruleKeys = []): string
    {
        $parts = [self::role($roleKey)];
        if ($ruleKeys) $parts[] = self::rules($ruleKeys);
        $parts[] = "你必须严格按 JSON 返回。任何说明性文字、Markdown 代码块、前后缀解释，都视为破坏契约。";
        return implode("\n\n", $parts);
    }
