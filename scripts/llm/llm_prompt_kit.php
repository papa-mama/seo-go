    /* ============================================================
     * 二、规则库（Rules Bundle）
     *   每条规则给"做什么"+"为什么"，让模型理解而非死记。
     * ============================================================ */
    public static function rules(array $keys): string
    {
        $bundle = [];
        foreach ($keys as $k) {
            if (isset(self::$RULES[$k])) $bundle[] = self::$RULES[$k];
        }
        return implode("\n", $bundle);
    }

